# Creates the .env file for the container on Windows, asking for passwords without showing them.
# The gateway password is stored only as a hash; the Prometheus/Zabbix token is generated and
# also saved to dev\metrics-token.txt (it is never printed).
# Needs a .venv with requirements.txt installed (for the password hash).
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File .\dev\make-env.ps1 -Out .\.env
# (-Out can also be a folder: the file will be called .env)
# On Linux/macOS, or without Python on Windows, follow the README instead.

param([Parameter(Mandatory = $true)][string]$Out)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$py = Join-Path $root '.venv\Scripts\python.exe'
if (-not (Test-Path $py)) { throw "No .venv: create it with  py -m venv .venv  and install requirements.txt" }
if (Test-Path $Out -PathType Container) { $Out = Join-Path $Out '.env' }

function Read-Secret($prompt) {
    $s = Read-Host $prompt -AsSecureString
    return [Net.NetworkCredential]::new('', $s).Password
}
function Ask($prompt, $default) {
    $v = Read-Host "$prompt [$default]"
    if ($v) { return $v } else { return $default }
}
function Quote($v) {
    # single quotes: docker compose does not expand '$' inside them (the hash contains some)
    if ($v -match "'") { throw "The value cannot contain single quotes" }
    return "'$v'"
}

if (Test-Path $Out) {
    if ((Ask "$Out already exists. Overwrite it? (y/n)" 'n') -ne 'y') { Write-Host 'Cancelled.'; exit 1 }
}

do { $bmcHost = Ask 'BMC address (IP or name)' $env:BMC_HOST } while (-not $bmcHost)
$bmcUser = Ask 'BMC user' $(if ($env:BMC_USER) { $env:BMC_USER } else { 'ADMIN' })
if ($env:BMC_PASSWORD -and (Ask 'Use the BMC password already set in this terminal? (y/n)' 'y') -eq 'y') {
    $bmcPass = $env:BMC_PASSWORD
} else {
    $bmcPass = Read-Secret 'BMC password'
}
$webUser = Ask 'User to sign in to the gateway' 'admin'
Write-Host 'Password to sign in to the gateway (twice):'
$hash = & $py -m webkvm hash-password
if ($LASTEXITCODE -ne 0 -or -not $hash) { throw 'password hash not generated' }
$vncPass = Read-Secret 'Native VNC password (max 8 characters, Enter = VNC off)'
$httpPort = Ask 'Dashboard port on the host' '8080'
$token = & $py -m webkvm gen-token

$lines = @(
    '# generated by dev/make-env.ps1 - contains secrets, do not share it',
    "BMC_HOST=$(Quote $bmcHost)",
    "BMC_USER=$(Quote $bmcUser)",
    "BMC_PASSWORD=$(Quote $bmcPass)",
    "WEBKVM_USER=$(Quote $webUser)",
    "WEBKVM_PASSWORD_HASH=$(Quote $hash)",
    "WEBKVM_METRICS_TOKEN=$(Quote $token)",
    "WEBKVM_HTTP_PORT=$httpPort",
    "VNC_ENABLE=$(if ($vncPass) { 'true' } else { 'false' })",
    "VNC_PASSWORD=$(Quote $vncPass)"
)
# UTF-8 without BOM and Unix line endings: with a BOM docker compose misreads the first variable
[IO.File]::WriteAllText($Out, ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
$tokenFile = Join-Path $root 'dev\metrics-token.txt'
[IO.File]::WriteAllText($tokenFile, $token + "`n", [Text.UTF8Encoding]::new($false))
Write-Host "Created $Out"
Write-Host "Token for Prometheus/Zabbix saved to $tokenFile"
